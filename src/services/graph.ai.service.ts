import { HumanMessage } from "@langchain/core/messages";
import { StateSchema, MessagesValue, ReducedValue, StateGraph, START, END, type GraphNode } from "@langchain/langgraph";
import { mistralModel, cohereModel, geminiModel } from "./models.service.js";
import { createAgent, providerStrategy } from "langchain"; // structured output nikalne ke kaam aata hai
import {z} from "zod"

// state ek node se dusre node pe jayegi toh uske pass ye yeh rahega like update hota jayega
// MessageValue -> jitne bhi message aap transfer karoge ek node se dusre node pe
// state -> generally data transfer from one node to another with the help of state
// State is a shared container that stores and updates data as it moves between different nodes in a LangGraph workflow.
// StateSchema defines what information needs to be stored and passed between these nodes.
// A reducer decides how new incoming data updates existing state data.

const State = new StateSchema({
    messages: MessagesValue,
    solution_1: new ReducedValue(z.string().default(""),{
        reducer:(current,next)=>{
            return next
        }
    }),
    solution_2: new ReducedValue(z.string().default(""),{
        reducer:(current,next)=>{
            return next
        }
    }),
    judge_recommendation: new ReducedValue(z.object().default({
        solution_1_score:0,
        solution_2_score:0
    }),
    {
        reducer: (current,next)=>{
            return next
        }
    }
)
});

const solutionNode:GraphNode<typeof State> = async(state: typeof State)=>{
    
    const [mistral_solution, cohere_solution] = await Promise.all([
        mistralModel.invoke(state.messages[0].content),
        cohereModel.invoke(state.messages[0].content)
    ])

    return {
        solution_1: mistral_solution.text,
        solution_2: cohere_solution.text
    }

}

const judgeNode:GraphNode<typeof State> = async(state: typeof State)=>{

    const {solution_1, solution_2} = state

    const judge = createAgent({
        model: geminiModel,
        tools: [],
        responseFormat: providerStrategy(z.object({
            solution_1_score: z.number().min(0).max(10),
            solution_2_score: z.number().min(0).max(10)
        }))
    })

    const judgeResponse = await judge.invoke({
        messages: [
        new HumanMessage(
            `You are a judge tasked with evaluating two solutions generated by different AI models. Please provide a score out of 10 for each solution, along with your reasoning for the scores.`
        )
    ]
    })

    const result = judgeResponse.structuredResponse

    return {
        judge_recommendation: result
    }

}

const graph = new StateGraph(State)
   .addNode("solution",solutionNode) // new node create kiya hai solution name ka 
   .addNode("judge", judgeNode)
   .addEdge(START, "solution") // edge bana di start or solution node ke beech me 
   .addEdge("solution","judge")
   .addEdge("judge", END)
   .compile()  // jab bhi graph banta hai compile krna padta hai (compulsory)

   export default async function (userMessage:string){
    const result = await graph.invoke({
        messages:[
            new HumanMessage(userMessage)
        ]
    })

    console.log(result)

    return result.messages
   }

